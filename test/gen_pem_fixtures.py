#!/usr/bin/env python3
"""Regenerates test/pem_fixtures.h, the PEM files pem_files.h's calls read.

Usage: python3 test/gen_pem_fixtures.py

The files are real ones, in the shapes an operator holds:

- pem_fixtures/r2_chain.pem: the corpus r2 chain, leaf first, as
  `openssl x509` writes each certificate, from webpki_corpus.h's
  Certificate message.
- pem_fixtures/bundle.pem: a CA bundle in curl's cacert.pem layout, a
  comment header and a name and a line of '=' above each root. The roots
  are the five public ones under test/webpki_captures/anchors/, and the
  corpus root_p384 that anchors the r2 chain.
- the r2 leaf's key, test/webpki_corpus/keys/leaf_p256.pem, as `openssl
  genpkey` wrote it (PKCS #8), and pem_fixtures/leaf_p256_sec1.pem, as
  `openssl ec` writes it (SEC 1);
- keys the calls refuse: pem_fixtures/leaf_p256_encrypted.pem (`openssl
  pkcs8 -topk8`, a password), the corpus P-384 and RSA-2048 keys, and
  pem_fixtures/leaf_p384_sec1.pem.
- EC PARAMETERS blocks, as `openssl ecparam` writes them:
  pem_fixtures/params_prime256v1.pem, the one a key file may hold, and
  pem_fixtures/params_secp384r1.pem and params_explicit.pem, which the key
  call refuses. pem_fixtures/leaf_p256_sec1_params.pem is the first of
  them above leaf_p256_sec1.pem, the shape `openssl ecparam -genkey`
  writes.
- pem_fixtures/genkey.pem, a fresh key as `openssl ecparam -name
  prime256v1 -genkey` writes it, the command the QUIC Interop Runner's
  certs.sh runs. pem_fixtures/genkey_sec1.der and genkey_spki.der hold its
  ECPrivateKey and its SubjectPublicKeyInfo as `openssl ec` writes them,
  so the test reads its scalar and its point from openssl's output.

- ML-DSA-87 key files and leaves, for test/pem_files_mldsa_test.c
  (docs/decisions.md 159), written to test/pem_fixtures_mldsa.h:
  pem_fixtures/mldsa87_both.pem, as `openssl genpkey -algorithm ML-DSA-87`
  writes it, the both form; mldsa87_seed.pem and mldsa87_expanded.pem, the
  same key as `openssl pkey` writes the seed-only and priv-only forms;
  mldsa87_leaf.der, a certificate of its key from `openssl req -x509`; and
  mldsa87_other_leaf.der, a certificate of another key. These need
  OpenSSL 3.5 or later, which $OPENSSL_MLDSA names, openssl by default.

- RSA key files and leaves, for test/pem_files_rsa_test.c
  (docs/decisions.md 184), written to test/pem_fixtures_rsa.h:
  pem_fixtures/rsa2048.pem, rsa3072.pem and rsa4096.pem, as `openssl
  genpkey -algorithm RSA` writes them (PKCS #8), and a certificate of each
  key from `openssl req -x509`; rsa2048_other_leaf.der, a certificate of
  another key; and keys the call refuses: rsa2048_pkcs1.pem, the first
  key as `openssl rsa -traditional` writes it (PKCS #1), rsa2048_e3.pem
  with the public exponent 3 and its certificate, rsa2048_3prime.pem with
  three primes, rsa2056.pem, whose modulus is 257 bytes, and its
  certificate, and rsa_pss.pem, an id-RSASSA-PSS key.

A file under pem_fixtures/ is written only when it is missing, with the
openssl command above, so the encrypted key's random salt stays put and a
run reproduces the header byte for byte. Delete a file to make it again.
The header holds every file as a C array of its bytes, and test/pem_files_test.c
reads them beside webpki_corpus.h's DER, which a different generator
extracts with openssl. The script runs the openssl CLI and opens no
network connection.
"""

import os
import pathlib
import re
import subprocess
import sys
import textwrap

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "pem_fixtures.h"
OUT_MLDSA = HERE / "pem_fixtures_mldsa.h"
OUT_RSA = HERE / "pem_fixtures_rsa.h"
OPENSSL_MLDSA = os.environ.get("OPENSSL_MLDSA", "openssl")
FIXTURES = HERE / "pem_fixtures"
CORPUS = HERE / "webpki_corpus.h"
KEYS = HERE / "webpki_corpus" / "keys"
ANCHORS = HERE / "webpki_captures" / "anchors"

# The captured roots, in the bundle's order, and the name curl's
# cacert.pem prints above each.
BUNDLE_ROOTS = [
    ("AmazonRootCA1.pem", "Amazon Root CA 1"),
    ("SFSRootCAG2.pem", "Starfield Services Root Certificate Authority - G2"),
    ("GTSRootR1.pem", "GTS Root R1"),
    ("GTSRootR4.pem", "GTS Root R4"),
    ("ISRGRootX2.pem", "ISRG Root X2"),
]

BUNDLE_HEADER = """##
## Bundle of CA Root Certificates
##
## A test fixture in the layout of curl's cacert.pem: comment lines, then
## a name and a line of '=' above each root. Generated by
## test/gen_pem_fixtures.py; regenerate, never edit.
##
"""


def corpus_array(name):
    """The bytes of one static const uint8_t array in webpki_corpus.h."""
    text = CORPUS.read_text()
    m = re.search(r"static const uint8_t " + re.escape(name) + r"\[\d+\] = \{(.*?)\};", text, re.S)
    if not m:
        sys.exit(f"gen_pem_fixtures: webpki_corpus.h has no array {name}")
    return bytes(int(h, 16) for h in re.findall(r"0x([0-9a-f]{2})", m.group(1)))


def certificate_entries(message):
    """The certificates of an RFC 9846 section 4.5.1 Certificate message:
    the handshake header, the empty context, the list, then entries of a
    u24 length, the certificate and an empty u16 extensions vector."""
    assert message[0] == 0x0B and message[4] == 0
    pos, end = 8, 8 + int.from_bytes(message[5:8], "big")
    out = []
    while pos < end:
        n = int.from_bytes(message[pos : pos + 3], "big")
        out.append(message[pos + 3 : pos + 3 + n])
        pos += 3 + n
        assert message[pos : pos + 2] == b"\x00\x00"
        pos += 2
    assert pos == end == len(message)
    return out


def armor(der):
    """One CERTIFICATE block as openssl x509 writes it: 64 characters a
    line and LF."""
    import base64

    body = base64.b64encode(der).decode()
    lines = textwrap.wrap(body, 64)
    return "-----BEGIN CERTIFICATE-----\n" + "\n".join(lines) + "\n-----END CERTIFICATE-----\n"


def openssl(args, path, tool="openssl"):
    """Writes path with openssl when it is missing."""
    if path.exists():
        return
    subprocess.run([tool, *args, "-out", str(path)], check=True, capture_output=True)
    print(f"gen_pem_fixtures: wrote {path.relative_to(HERE.parent)}")


def write_if_missing(path, text):
    if path.exists():
        return
    path.write_text(text)
    print(f"gen_pem_fixtures: wrote {path.relative_to(HERE.parent)}")


def c_bytes(symbol, data):
    """A C array of data's bytes, sixteen a line. A string literal would
    pass ISO C's 4095-character floor, which -Wpedantic holds."""
    lines = [f"static const uint8_t {symbol}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    FIXTURES.mkdir(exist_ok=True)
    r2 = certificate_entries(corpus_array("webpki_corpus_message_r2"))
    letsencrypt = certificate_entries(corpus_array("webpki_corpus_message_letsencrypt"))
    root_p384 = letsencrypt[-1]

    write_if_missing(FIXTURES / "r2_chain.pem", "".join(armor(cert) for cert in r2))
    bundle = BUNDLE_HEADER
    for file, name in BUNDLE_ROOTS:
        bundle += f"\n{name}\n{'=' * len(name)}\n" + (ANCHORS / file).read_text()
    bundle += "\nCorpus Root P-384\n=================\n" + armor(root_p384)
    write_if_missing(FIXTURES / "bundle.pem", bundle)
    openssl(["ec", "-in", str(KEYS / "leaf_p256.pem")], FIXTURES / "leaf_p256_sec1.pem")
    openssl(["ec", "-in", str(KEYS / "leaf_p384.pem")], FIXTURES / "leaf_p384_sec1.pem")
    openssl(
        ["pkcs8", "-topk8", "-v2", "aes-256-cbc", "-passout", "pass:fixture", "-in", str(KEYS / "leaf_p256.pem")],
        FIXTURES / "leaf_p256_encrypted.pem",
    )
    openssl(["ecparam", "-name", "prime256v1"], FIXTURES / "params_prime256v1.pem")
    openssl(["ecparam", "-name", "secp384r1"], FIXTURES / "params_secp384r1.pem")
    openssl(["ecparam", "-name", "prime256v1", "-param_enc", "explicit"], FIXTURES / "params_explicit.pem")
    write_if_missing(
        FIXTURES / "leaf_p256_sec1_params.pem",
        (FIXTURES / "params_prime256v1.pem").read_text() + (FIXTURES / "leaf_p256_sec1.pem").read_text(),
    )
    openssl(["ecparam", "-name", "prime256v1", "-genkey"], FIXTURES / "genkey.pem")
    openssl(["ec", "-in", str(FIXTURES / "genkey.pem"), "-outform", "DER"], FIXTURES / "genkey_sec1.der")
    openssl(["ec", "-in", str(FIXTURES / "genkey.pem"), "-pubout", "-outform", "DER"], FIXTURES / "genkey_spki.der")

    files = [
        ("pem_fixture_r2_chain", FIXTURES / "r2_chain.pem"),
        ("pem_fixture_bundle", FIXTURES / "bundle.pem"),
        ("pem_fixture_key_pkcs8", KEYS / "leaf_p256.pem"),
        ("pem_fixture_key_sec1", FIXTURES / "leaf_p256_sec1.pem"),
        ("pem_fixture_key_encrypted", FIXTURES / "leaf_p256_encrypted.pem"),
        ("pem_fixture_key_p384_pkcs8", KEYS / "leaf_p384.pem"),
        ("pem_fixture_key_p384_sec1", FIXTURES / "leaf_p384_sec1.pem"),
        ("pem_fixture_key_rsa_pkcs8", KEYS / "leaf_rsa2048.pem"),
        ("pem_fixture_params_prime256v1", FIXTURES / "params_prime256v1.pem"),
        ("pem_fixture_params_secp384r1", FIXTURES / "params_secp384r1.pem"),
        ("pem_fixture_params_explicit", FIXTURES / "params_explicit.pem"),
        ("pem_fixture_key_sec1_params", FIXTURES / "leaf_p256_sec1_params.pem"),
        ("pem_fixture_genkey", FIXTURES / "genkey.pem"),
        ("pem_fixture_genkey_sec1", FIXTURES / "genkey_sec1.der"),
        ("pem_fixture_genkey_spki", FIXTURES / "genkey_spki.der"),
    ]
    parts = [
        "// The PEM files test/pem_files_test.c decodes. Generated by",
        "// test/gen_pem_fixtures.py from the files under test/pem_fixtures/, the",
        "// corpus keys and the captured roots; regenerate, never edit.",
        "#ifndef CH_TEST_PEM_FIXTURES_H",
        "#define CH_TEST_PEM_FIXTURES_H",
        "",
        "#include <stdint.h>",
        "",
        "// clang-format off",
    ]
    for symbol, path in files:
        parts.append(f"// {path.relative_to(HERE.parent)}")
        parts.append(c_bytes(symbol, path.read_bytes()))
        parts.append("")
    parts += ["// clang-format on", "", "#endif", ""]
    OUT.write_text("\n".join(parts))
    print(f"gen_pem_fixtures: wrote {OUT.relative_to(HERE.parent)}")
    mldsa_fixtures()
    rsa_fixtures()


def der_integers(der):
    """The INTEGERs of a PKCS #8 RSA key's RSAPrivateKey, as Python ints,
    read with a reader of its own: version, n, e, d, p, q, dp, dq, qinv."""
    def tlv(buf, pos):
        tag, n = buf[pos], buf[pos + 1]
        pos += 2
        if n & 0x80:
            k = n & 0x7F
            n = int.from_bytes(buf[pos : pos + k], "big")
            pos += k
        return tag, buf[pos : pos + n], pos + n

    _, info, _ = tlv(der, 0)
    pos = 0
    for _ in range(2):  # version, AlgorithmIdentifier
        _, _, pos = tlv(info, pos)
    tag, octets, _ = tlv(info, pos)
    assert tag == 0x04
    _, key, _ = tlv(octets, 0)
    values, pos = [], 0
    while pos < len(key):
        tag, body, pos = tlv(key, pos)
        assert tag == 0x02
        values.append(int.from_bytes(body, "big"))
    return values


def rsa_fixtures():
    """The RSA files and test/pem_fixtures_rsa.h."""
    def genpkey(name, *opts, algorithm="RSA"):
        args = ["genpkey", "-algorithm", algorithm]
        for opt in opts:
            args += ["-pkeyopt", opt]
        openssl(args, FIXTURES / name)

    def leaf(key, name):
        openssl(["req", "-x509", "-new", "-key", str(FIXTURES / key), "-subj", "/CN=leaf", "-days",
                 "3650", "-outform", "DER"], FIXTURES / name)

    for bits in (2048, 3072, 4096):
        genpkey(f"rsa{bits}.pem", f"rsa_keygen_bits:{bits}")
        leaf(f"rsa{bits}.pem", f"rsa{bits}_leaf.der")
    genpkey("rsa2048_other.pem", "rsa_keygen_bits:2048")
    leaf("rsa2048_other.pem", "rsa2048_other_leaf.der")
    openssl(["rsa", "-traditional", "-in", str(FIXTURES / "rsa2048.pem")], FIXTURES / "rsa2048_pkcs1.pem")
    genpkey("rsa2048_e3.pem", "rsa_keygen_bits:2048", "rsa_keygen_pubexp:3")
    leaf("rsa2048_e3.pem", "rsa2048_e3_leaf.der")
    genpkey("rsa2048_3prime.pem", "rsa_keygen_bits:2048", "rsa_keygen_primes:3")
    leaf("rsa2048_3prime.pem", "rsa2048_3prime_leaf.der")
    genpkey("rsa2056.pem", "rsa_keygen_bits:2056")
    leaf("rsa2056.pem", "rsa2056_leaf.der")
    genpkey("rsa_pss.pem", "rsa_keygen_bits:2048", algorithm="RSA-PSS")
    files = [("pem_fixture_rsa2048", "rsa2048.pem"), ("pem_fixture_rsa2048_leaf", "rsa2048_leaf.der"),
             ("pem_fixture_rsa3072", "rsa3072.pem"), ("pem_fixture_rsa3072_leaf", "rsa3072_leaf.der"),
             ("pem_fixture_rsa4096", "rsa4096.pem"), ("pem_fixture_rsa4096_leaf", "rsa4096_leaf.der"),
             ("pem_fixture_rsa2048_other_leaf", "rsa2048_other_leaf.der"),
             ("pem_fixture_rsa2048_pkcs1", "rsa2048_pkcs1.pem"),
             ("pem_fixture_rsa2048_e3", "rsa2048_e3.pem"), ("pem_fixture_rsa2048_e3_leaf", "rsa2048_e3_leaf.der"),
             ("pem_fixture_rsa2048_3prime", "rsa2048_3prime.pem"),
             ("pem_fixture_rsa2048_3prime_leaf", "rsa2048_3prime_leaf.der"),
             ("pem_fixture_rsa2056", "rsa2056.pem"), ("pem_fixture_rsa2056_leaf", "rsa2056_leaf.der"),
             ("pem_fixture_rsa_pss", "rsa_pss.pem")]
    parts = [
        "// The RSA files test/pem_files_rsa_test.c decodes. Generated by",
        "// test/gen_pem_fixtures.py from the files under test/pem_fixtures/;",
        "// regenerate, never edit.",
        "#ifndef CH_TEST_PEM_FIXTURES_RSA_H",
        "#define CH_TEST_PEM_FIXTURES_RSA_H",
        "",
        "#include <stdint.h>",
        "",
        "// clang-format off",
    ]
    for symbol, name in files:
        path = FIXTURES / name
        parts.append(f"// {path.relative_to(HERE.parent)}")
        parts.append(c_bytes(symbol, path.read_bytes()))
        parts.append("")
    der = subprocess.run(["openssl", "pkey", "-in", str(FIXTURES / "rsa2048.pem"), "-outform", "DER"],
                         check=True, capture_output=True).stdout
    _, n, e, d, p, q, dp, dq, qinv = der_integers(der)
    assert e == 65537 and p * q == n and d * e % ((p - 1) * (q - 1) // __import__("math").gcd(p - 1, q - 1)) == 1
    parts.append("// rsa2048.pem's integers, big-endian at rsa_sign.h's lengths, from openssl's DER")
    for symbol, value, width in (("n", n, 256), ("d", d, 256), ("p", p, 128), ("q", q, 128),
                                 ("dp", dp, 128), ("dq", dq, 128), ("qinv", qinv, 128)):
        parts.append(c_bytes(f"pem_fixture_rsa2048_{symbol}", value.to_bytes(width, "big")))
        parts.append("")
    parts += ["// clang-format on", "", "#endif", ""]
    OUT_RSA.write_text("\n".join(parts))
    print(f"gen_pem_fixtures: wrote {OUT_RSA.relative_to(HERE.parent)}")


def mldsa_fixtures():
    """The ML-DSA-87 files and test/pem_fixtures_mldsa.h."""
    both = FIXTURES / "mldsa87_both.pem"
    other = FIXTURES / "mldsa87_other.pem"
    openssl(["genpkey", "-algorithm", "ML-DSA-87"], both, OPENSSL_MLDSA)
    openssl(["genpkey", "-algorithm", "ML-DSA-87"], other, OPENSSL_MLDSA)
    openssl(["pkey", "-in", str(both), "-provparam", "ml-dsa.output_formats=seed-only"],
            FIXTURES / "mldsa87_seed.pem", OPENSSL_MLDSA)
    openssl(["pkey", "-in", str(both), "-provparam", "ml-dsa.output_formats=priv-only"],
            FIXTURES / "mldsa87_expanded.pem", OPENSSL_MLDSA)
    for key, leaf in ((both, "mldsa87_leaf.der"), (other, "mldsa87_other_leaf.der")):
        openssl(["req", "-x509", "-new", "-key", str(key), "-subj", "/CN=leaf", "-days", "3650",
                 "-outform", "DER"], FIXTURES / leaf, OPENSSL_MLDSA)
    files = [
        ("pem_fixture_mldsa_both", both),
        ("pem_fixture_mldsa_seed", FIXTURES / "mldsa87_seed.pem"),
        ("pem_fixture_mldsa_expanded", FIXTURES / "mldsa87_expanded.pem"),
        ("pem_fixture_mldsa_leaf", FIXTURES / "mldsa87_leaf.der"),
        ("pem_fixture_mldsa_other_leaf", FIXTURES / "mldsa87_other_leaf.der"),
    ]
    parts = [
        "// The ML-DSA-87 files test/pem_files_mldsa_test.c decodes. Generated by",
        "// test/gen_pem_fixtures.py from the files under test/pem_fixtures/;",
        "// regenerate, never edit.",
        "#ifndef CH_TEST_PEM_FIXTURES_MLDSA_H",
        "#define CH_TEST_PEM_FIXTURES_MLDSA_H",
        "",
        "#include <stdint.h>",
        "",
        "// clang-format off",
    ]
    for symbol, path in files:
        parts.append(f"// {path.relative_to(HERE.parent)}")
        parts.append(c_bytes(symbol, path.read_bytes()))
        parts.append("")
    parts += ["// clang-format on", "", "#endif", ""]
    OUT_MLDSA.write_text("\n".join(parts))
    print(f"gen_pem_fixtures: wrote {OUT_MLDSA.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Convert Wycheproof's Ed25519 suite into a C header for
test/wycheproof_ed25519_test.c.

Usage: gen_wycheproof_ed25519.py <wycheproof-checkout> <output.h>

The suite is testvectors_v1/ed25519_test.json at the commit
tools/toolchain.env pins, the checkout make wycheproof already fetches.
Each case is a public key, a message, a signature and a verdict: valid,
invalid, or acceptable, which leaves the case to the implementation. The
script writes what chapulin's rule gives each acceptable case, by the
case's flags (docs/decisions.md 227): the rule refuses a small-order key
and a key outside the subgroup of prime order. An acceptable case with
any other flag stops the script, so a new kind of case gets a rule before
it gets a verdict. The output lands in bin/, never in the tree, as
gen_wycheproof.py's does, and every hex block is checked against its
declared length where the suite declares one.
"""

import json
import sys
from pathlib import Path


# The flags of the acceptable cases that chapulin's rule refuses.
REFUSED_FLAGS = {"SmallOrderPublicKey", "MixedOrderPublicKey"}


def c_bytes(data):
    return ", ".join("0x%02x" % b for b in data) if data else "0"


def verdict(test):
    """2 for a case Wycheproof leaves to the implementation and chapulin's
    rule refuses, 1 for a valid case and 0 for an invalid one."""
    if test["result"] == "valid":
        return 1
    if test["result"] == "invalid":
        return 0
    flags = set(test.get("flags", []))
    if test["result"] == "acceptable" and flags and flags <= REFUSED_FLAGS:
        return 2
    raise SystemExit("tcId %d: no rule for the result %s with the flags %s"
                     % (test["tcId"], test["result"], sorted(flags)))


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    suite = json.load(open(src / "testvectors_v1" / "ed25519_test.json"))
    blobs = []
    rows = []
    for group in suite["testGroups"]:
        key = bytes.fromhex(group["publicKey"]["pk"])
        if len(key) != 32:
            raise SystemExit("a public key of %d bytes" % len(key))
        for test in group["tests"]:
            i = len(rows)
            msg = bytes.fromhex(test["msg"])
            sig = bytes.fromhex(test["sig"])
            blobs.append("static const uint8_t wp_ed_key_%d[32] = {%s};" % (i, c_bytes(key)))
            blobs.append("static const uint8_t wp_ed_msg_%d[%d] = {%s};" % (i, max(len(msg), 1), c_bytes(msg)))
            blobs.append("static const uint8_t wp_ed_sig_%d[%d] = {%s};" % (i, max(len(sig), 1), c_bytes(sig)))
            rows.append("    {%d, wp_ed_key_%d, wp_ed_msg_%d, %d, wp_ed_sig_%d, %d, %d},"
                        % (test["tcId"], i, i, len(msg), i, len(sig), verdict(test)))
    lines = ["// Generated by test/gen_wycheproof_ed25519.py from Wycheproof's ed25519_test.json.",
             "#ifndef CH_WYCHEPROOF_ED25519_VECTORS_H", "#define CH_WYCHEPROOF_ED25519_VECTORS_H", "",
             "#include <stddef.h>", "#include <stdint.h>", ""]
    lines += blobs
    lines += ["", "static const struct {", "    int tc_id;", "    const uint8_t *key;",
              "    const uint8_t *msg;", "    size_t msg_len;", "    const uint8_t *sig;",
              "    size_t sig_len;",
              "    int kind; // 1 valid, 0 invalid, 2 left to the implementation and refused",
              "} wp_ed25519[] = {"]
    lines += rows
    lines += ["};", "", "#endif", ""]
    out.write_text("\n".join(lines))
    print("gen_wycheproof_ed25519: %d cases" % len(rows))


if __name__ == "__main__":
    main()

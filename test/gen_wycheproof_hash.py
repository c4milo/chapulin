#!/usr/bin/env python3
"""Convert Wycheproof's suites for hash.h's HMAC and HKDF into a C header
for test/wycheproof_hash_test.c.

Usage: gen_wycheproof_hash.py <wycheproof-checkout> <output.h>

The suites are in testvectors_v1/ at the commit tools/toolchain.env pins,
the checkout make wycheproof already fetches:

- hmac_sha256_test.json, hmac_sha384_test.json and hmac_sha512_test.json:
  a key, a message and a tag, which a group may cut to its tagSize bits.
  A valid case's tag is the HMAC's first bytes, and an invalid case's tag
  is not.
- hkdf_sha256_test.json, hkdf_sha384_test.json and hkdf_sha512_test.json:
  ikm, salt, info, the size of the output and the output. An invalid case
  asks for more than 255 blocks, which ch_hkdf_expand refuses.

Wycheproof has no suite for SHA-2, SHA-3 or SHAKE alone. The output lands
in bin/, never in the tree, as gen_wycheproof.py's does.
"""

import json
import sys
from pathlib import Path

# hash.h's algorithm numbers, by the hash each suite names.
ALGORITHMS = {"sha256": 1, "sha384": 2, "sha512": 3}


def c_bytes(data):
    return ", ".join("0x%02x" % b for b in data) if data else "0"


class Blobs:
    """Each byte string once, as a static array a row points at."""

    def __init__(self):
        self.lines = []

    def __call__(self, data):
        name = "wp_hash_blob_%d" % len(self.lines)
        self.lines.append("static const uint8_t %s[%d] = {%s};" % (name, max(len(data), 1),
                                                                    c_bytes(data)))
        return name


def verdict(test):
    if test["result"] not in ("valid", "invalid"):
        raise SystemExit("a case with the result " + test["result"])
    return 1 if test["result"] == "valid" else 0


def hmac_rows(src, blob):
    rows = []
    for name, algorithm in ALGORITHMS.items():
        suite = json.load(open(src / ("hmac_%s_test.json" % name)))
        for group in suite["testGroups"]:
            if group["tagSize"] % 8 != 0:
                raise SystemExit("a tag of %d bits" % group["tagSize"])
            for test in group["tests"]:
                key, msg, tag = (bytes.fromhex(test[k]) for k in ("key", "msg", "tag"))
                rows.append("    {%d, %d, %s, %d, %s, %d, %s, %d, %d, %d},"
                            % (test["tcId"], algorithm, blob(key), len(key), blob(msg), len(msg),
                               blob(tag), len(tag), group["tagSize"] // 8, verdict(test)))
    return rows


def hkdf_rows(src, blob):
    rows = []
    for name, algorithm in ALGORITHMS.items():
        suite = json.load(open(src / ("hkdf_%s_test.json" % name)))
        for group in suite["testGroups"]:
            for test in group["tests"]:
                ikm, salt, info, okm = (bytes.fromhex(test[k])
                                        for k in ("ikm", "salt", "info", "okm"))
                rows.append("    {%d, %d, %s, %d, %s, %d, %s, %d, %d, %s, %d, %d},"
                            % (test["tcId"], algorithm, blob(ikm), len(ikm), blob(salt), len(salt),
                               blob(info), len(info), test["size"], blob(okm), len(okm),
                               verdict(test)))
    return rows


def main():
    src, out = Path(sys.argv[1]) / "testvectors_v1", Path(sys.argv[2])
    blob = Blobs()
    hmacs = hmac_rows(src, blob)
    hkdfs = hkdf_rows(src, blob)
    lines = ["// Generated by test/gen_wycheproof_hash.py from Wycheproof's suites.",
             "#ifndef CH_WYCHEPROOF_HASH_VECTORS_H", "#define CH_WYCHEPROOF_HASH_VECTORS_H", "",
             "#include <stddef.h>", "#include <stdint.h>", ""]
    lines += blob.lines
    lines += ["", "// tag holds tag_len bytes, and a valid case's are the first tag_size",
              "// bytes of the HMAC under algorithm, hash.h's number.",
              "static const struct {", "    int tc_id;", "    uint8_t algorithm;",
              "    const uint8_t *key;", "    size_t key_len;", "    const uint8_t *msg;",
              "    size_t msg_len;", "    const uint8_t *tag;", "    size_t tag_len;",
              "    size_t tag_size;", "    int valid;", "} wp_hmac[] = {"]
    lines += hmacs
    lines += ["};", "", "// size is the output's length, which an invalid case's exceeds.",
              "static const struct {", "    int tc_id;", "    uint8_t algorithm;",
              "    const uint8_t *ikm;", "    size_t ikm_len;", "    const uint8_t *salt;",
              "    size_t salt_len;", "    const uint8_t *info;", "    size_t info_len;",
              "    size_t size;", "    const uint8_t *okm;", "    size_t okm_len;", "    int valid;",
              "} wp_hkdf[] = {"]
    lines += hkdfs
    lines += ["};", "", "#endif", ""]
    out.write_text("\n".join(lines))
    print("gen_wycheproof_hash: %d HMAC cases, %d HKDF cases" % (len(hmacs), len(hkdfs)))


if __name__ == "__main__":
    main()

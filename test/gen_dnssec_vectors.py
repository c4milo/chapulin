#!/usr/bin/env python3
"""Regenerates test/dnssec_vectors.h.

Usage: python3 test/gen_dnssec_vectors.py

ch_dnssec_verify checks an RRSIG signature against a DNSKEY's key field
(https://github.com/c4milo/chapulin/issues/189). This script mints keys
and signatures with OpenSSL and writes them in the forms DNSSEC carries:

- RSA, algorithms 8 and 10: the key field of RFC 3110 section 2, an
  exponent length, the exponent and the modulus, each without leading
  zero bytes, and a PKCS#1 v1.5 signature over SHA-256 or SHA-512 (RFC
  5702 section 3). The keys cover 512 bits, the floor RFC 5702's example
  uses, a length that is no whole number of 8-byte words, 2048 and 4096
  bits, and the exponents 3 and 65537.
- ECDSA P-256, algorithm 13: the 64 bytes of X then Y, and r then s,
  32 bytes each (RFC 6605 section 4), which the script takes out of
  OpenSSL's DER.
- Ed25519, algorithm 15: the 32-byte public key and the 64-byte
  signature R then S (RFC 8080 section 3). The digest is RFC 8032
  section 5.1.7's: SHA-512 of R, the key and the message, the bytes
  ch_dnssec_hash_final writes for algorithm 15.

The commands, per key:

  openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:<bits>
    -pkeyopt rsa_keygen_pubexp:<e> -out key.pem
  openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out key.pem
  openssl genpkey -algorithm ED25519 -out key.pem
  openssl pkeyutl -sign -rawin -inkey key.pem -in msg -out sig
  openssl pkeyutl -verify -rawin -pubin -inkey pub.pem -in msg -sigfile sig
  openssl dgst -<sha256|sha512> -sign key.pem -out sig msg
  openssl dgst -<sha256|sha512> -verify pub.pem -signature sig msg

Every signature is verified with OpenSSL before it is written. The keys
are fresh on every run, so the header changes when it is regenerated;
vectors are regenerate-never-edit snapshots.
"""

import hashlib
import pathlib
import subprocess
import tempfile

HERE = pathlib.Path(__file__).parent
OUT = HERE / "dnssec_vectors.h"

# (algorithm, bits, exponent, message)
RSA_KEYS = [
    (8, 512, 3, b"chapulin dnssec rsasha256 512 e=3"),
    (8, 1032, 65537, b"chapulin dnssec rsasha256 1032"),
    (8, 4096, 3, b"chapulin dnssec rsasha256 4096 e=3"),
    (10, 1024, 65537, b"chapulin dnssec rsasha512 1024"),
    (10, 2048, 3, b"chapulin dnssec rsasha512 2048 e=3"),
]
EC_MESSAGES = [b"chapulin dnssec ecdsap256sha256 one", b"chapulin dnssec ecdsap256sha256 two"]
ED_MESSAGES = [b"chapulin dnssec ed25519 one", b"chapulin dnssec ed25519 two, a longer message"]


def run(*args, data=None):
    return subprocess.run(args, input=data, capture_output=True, check=True).stdout


def unhex(text):
    return bytes.fromhex("".join(text.split()).replace(":", ""))


def rsa_numbers(key):
    text = run("openssl", "pkey", "-in", key, "-noout", "-text").decode()
    mod = text.split("modulus:")[1].split("publicExponent:")[0]
    exp = int(text.split("publicExponent:")[1].split()[0])
    n = unhex(mod).lstrip(b"\x00")
    return n, exp


def minimal(value):
    return value.to_bytes((value.bit_length() + 7) // 8, "big")


def der_integers(der):
    """r and s out of an ECDSA-Sig-Value, each as 32 bytes."""
    assert der[0] == 0x30
    i = 2
    out = []
    for _ in range(2):
        assert der[i] == 0x02
        n = der[i + 1]
        out.append(der[i + 2:i + 2 + n].lstrip(b"\x00").rjust(32, b"\x00"))
        i += 2 + n
    return out[0] + out[1]


def sign(tmp, key, digest_name, msg):
    msg_path = tmp / "msg"
    msg_path.write_bytes(msg)
    sig_path = tmp / "sig"
    pub_path = tmp / "pub.pem"
    run("openssl", "dgst", "-" + digest_name, "-sign", key, "-out", str(sig_path), str(msg_path))
    run("openssl", "pkey", "-in", key, "-pubout", "-out", str(pub_path))
    run("openssl", "dgst", "-" + digest_name, "-verify", str(pub_path), "-signature",
        str(sig_path), str(msg_path))
    return sig_path.read_bytes()


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return "static const uint8_t %s[%d] = {\n%s\n};\n" % (name, len(data), "\n".join(lines))


def main():
    out = [
        "// Generated by test/gen_dnssec_vectors.py; regenerate, never edit.",
        "#ifndef CH_DNSSEC_VECTORS_H",
        "#define CH_DNSSEC_VECTORS_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]
    rows = []
    with tempfile.TemporaryDirectory() as d:
        tmp = pathlib.Path(d)
        key = str(tmp / "key.pem")
        index = 0
        for alg, bits, e, msg in RSA_KEYS:
            run("openssl", "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:%d" % bits,
                "-pkeyopt", "rsa_keygen_pubexp:%d" % e, "-out", key)
            n, exp = rsa_numbers(key)
            assert exp == e
            e_bytes = minimal(e)
            field = bytes([len(e_bytes)]) + e_bytes + n
            digest_name = "sha256" if alg == 8 else "sha512"
            digest = hashlib.new(digest_name, msg).digest()
            sig = sign(tmp, key, digest_name, msg)
            assert len(sig) == len(n)
            out += [c_array("dnssec_key_%d" % index, field),
                    c_array("dnssec_digest_%d" % index, digest),
                    c_array("dnssec_sig_%d" % index, sig)]
            rows.append((alg, index))
            index += 1
        for msg in EC_MESSAGES:
            run("openssl", "genpkey", "-algorithm", "EC", "-pkeyopt",
                "ec_paramgen_curve:P-256", "-out", key)
            pub_der = run("openssl", "pkey", "-in", key, "-pubout", "-outform", "DER")
            assert pub_der[-65] == 0x04
            field = pub_der[-64:]
            digest = hashlib.sha256(msg).digest()
            sig = der_integers(sign(tmp, key, "sha256", msg))
            out += [c_array("dnssec_key_%d" % index, field),
                    c_array("dnssec_digest_%d" % index, digest),
                    c_array("dnssec_sig_%d" % index, sig)]
            rows.append((13, index))
            index += 1
        for msg in ED_MESSAGES:
            run("openssl", "genpkey", "-algorithm", "ED25519", "-out", key)
            msg_path = tmp / "msg"
            msg_path.write_bytes(msg)
            pub_path = tmp / "pub.pem"
            sig_path = tmp / "sig"
            run("openssl", "pkey", "-in", key, "-pubout", "-out", str(pub_path))
            run("openssl", "pkeyutl", "-sign", "-rawin", "-inkey", key, "-in", str(msg_path),
                "-out", str(sig_path))
            run("openssl", "pkeyutl", "-verify", "-rawin", "-pubin", "-inkey", str(pub_path),
                "-in", str(msg_path), "-sigfile", str(sig_path))
            field = run("openssl", "pkey", "-in", key, "-pubout", "-outform", "DER")[-32:]
            sig = sig_path.read_bytes()
            assert len(sig) == 64
            digest = hashlib.sha512(sig[:32] + field + msg).digest()
            out += [c_array("dnssec_key_%d" % index, field),
                    c_array("dnssec_digest_%d" % index, digest),
                    c_array("dnssec_sig_%d" % index, sig)]
            rows.append((15, index))
            index += 1
    out += [
        "typedef struct {",
        "    uint8_t algorithm;",
        "    const uint8_t *key;",
        "    size_t key_len;",
        "    const uint8_t *digest;",
        "    size_t digest_len;",
        "    const uint8_t *sig;",
        "    size_t sig_len;",
        "} dnssec_vector;",
        "",
        "static const dnssec_vector dnssec_vectors[] = {",
    ]
    for alg, i in rows:
        out.append("    {%d, dnssec_key_%d, sizeof dnssec_key_%d, dnssec_digest_%d, "
                   "sizeof dnssec_digest_%d, dnssec_sig_%d, sizeof dnssec_sig_%d},"
                   % (alg, i, i, i, i, i, i))
    out += ["};", "", "#endif", ""]
    OUT.write_text("\n".join(out))


if __name__ == "__main__":
    main()

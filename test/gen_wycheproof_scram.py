#!/usr/bin/env python3
"""Convert Wycheproof's suites for scram.h's calls into a C header for
test/wycheproof_scram_test.c.

Usage: gen_wycheproof_scram.py <wycheproof-checkout> <output.h>

The suites are in testvectors_v1/ at the commit tools/toolchain.env pins,
the checkout make wycheproof already fetches:

- hmac_sha256_test.json: a key, a message and a tag, which a group may
  cut to its tagSize bits. A valid case's tag is HMAC-SHA-256's first
  bytes, and an invalid case's tag is not.
- pbkdf2_hmacsha256_test.json: a password, a salt, an iteration count and
  the derived key.

Wycheproof has no suite for SHA-256 alone, for base64 or for the
tls-server-end-point value. The output lands in bin/, never in the tree,
as gen_wycheproof.py's does.
"""

import json
import sys
from pathlib import Path


def c_bytes(data):
    return ", ".join("0x%02x" % b for b in data) if data else "0"


def main():
    src, out = Path(sys.argv[1]) / "testvectors_v1", Path(sys.argv[2])
    blobs = []

    def blob(data):
        name = "wp_scram_blob_%d" % len(blobs)
        blobs.append("static const uint8_t %s[%d] = {%s};" % (name, max(len(data), 1),
                                                              c_bytes(data)))
        return name

    hmacs = []
    suite = json.load(open(src / "hmac_sha256_test.json"))
    for group in suite["testGroups"]:
        tag_len = group["tagSize"] // 8
        if group["tagSize"] % 8 != 0 or not 1 <= tag_len <= 32:
            raise SystemExit("a tag of %d bits" % group["tagSize"])
        for test in group["tests"]:
            key, msg, tag = (bytes.fromhex(test[k]) for k in ("key", "msg", "tag"))
            if test["result"] not in ("valid", "invalid"):
                raise SystemExit("an HMAC case with the result " + test["result"])
            hmacs.append("    {%d, %s, %d, %s, %d, %s, %d, %d, %d},"
                         % (test["tcId"], blob(key), len(key), blob(msg), len(msg), blob(tag),
                            len(tag), tag_len, 1 if test["result"] == "valid" else 0))

    keys = []
    suite = json.load(open(src / "pbkdf2_hmacsha256_test.json"))
    for group in suite["testGroups"]:
        for test in group["tests"]:
            password, salt, dk = (bytes.fromhex(test[k]) for k in ("password", "salt", "dk"))
            if test["result"] != "valid" or len(dk) != test["dkLen"]:
                raise SystemExit("a PBKDF2 case that is not a valid key of dkLen bytes")
            keys.append("    {%d, %s, %d, %s, %d, %d, %s, %d},"
                        % (test["tcId"], blob(password), len(password), blob(salt), len(salt),
                           test["iterationCount"], blob(dk), len(dk)))

    lines = ["// Generated by test/gen_wycheproof_scram.py from Wycheproof's suites.",
             "#ifndef CH_WYCHEPROOF_SCRAM_VECTORS_H", "#define CH_WYCHEPROOF_SCRAM_VECTORS_H", "",
             "#include <stddef.h>", "#include <stdint.h>", ""]
    lines += blobs
    lines += ["", "// tag holds tag_len bytes, and a valid case's are the first tag_size",
              "// bytes of HMAC-SHA-256.",
              "static const struct {", "    int tc_id;", "    const uint8_t *key;",
              "    size_t key_len;", "    const uint8_t *msg;", "    size_t msg_len;",
              "    const uint8_t *tag;", "    size_t tag_len;", "    size_t tag_size;",
              "    int valid;", "} wp_hmac[] = {"]
    lines += hmacs
    lines += ["};", "", "static const struct {", "    int tc_id;", "    const uint8_t *password;",
              "    size_t password_len;", "    const uint8_t *salt;", "    size_t salt_len;",
              "    uint32_t iteration_count;", "    const uint8_t *key;", "    size_t key_len;",
              "} wp_pbkdf2[] = {"]
    lines += keys
    lines += ["};", "", "#endif", ""]
    out.write_text("\n".join(lines))
    print("gen_wycheproof_scram: %d HMAC cases, %d PBKDF2 cases" % (len(hmacs), len(keys)))


if __name__ == "__main__":
    main()

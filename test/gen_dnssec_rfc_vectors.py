def wire_name(name):
    out = b""
    for label in name.rstrip(".").split("."):
        out += bytes([len(label)]) + label.lower().encode()
    return out + b"\x00"


def seconds(stamp):
    return calendar.timegm(time.strptime(stamp, "%Y%m%d%H%M%S"))


def signed_data(algorithm, key_tag, expiration, inception, address):
    rrsig = struct.pack(">HBBIIIH", TYPE_A, algorithm, 3, 3600, seconds(expiration),
                        seconds(inception), key_tag) + wire_name("example.net.")
    record = wire_name("www.example.net.") + struct.pack(">HHIH", TYPE_A, CLASS_IN, 3600, 4)
    return rrsig + record + bytes(address)


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return "static const uint8_t %s[%d] = {\n%s\n};\n" % (name, len(data), "\n".join(lines))



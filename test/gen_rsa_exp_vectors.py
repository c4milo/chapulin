#!/usr/bin/env python3
"""Regenerates test/rsa_exp_vectors.h.

Usage: python3 test/gen_rsa_exp_vectors.py

rsa_mont64_public_exp computes base^e mod m for the exponent a DNSSEC key
names (RFC 3110 section 2). This script writes known answers for it,
computed with Python's own pow, which shares no code with the C.

Each vector is an odd modulus whose top bit is set, a base of the
modulus's length, an odd exponent of 3 to 64 bits, and pow(base, e, m).
The moduli are odd numbers and not RSA moduli: Montgomery arithmetic needs
an odd modulus and nothing more, so the answers test the arithmetic alone.
The lengths cover 64 bytes, the floor the DNSSEC entry admits, lengths that
are not a whole number of 8-byte words, and 512 bytes, the TRUST=webpki
bound. The exponents cover 3, 65537, single-bit runs and 2^64 - 1. Some
bases are at or above the modulus, which the call takes.

The generator is seeded, so a rerun writes the same header.
"""

import random

LENGTHS = [64, 65, 71, 72, 100, 128, 129, 256, 384, 512]
EXPONENTS = [3, 5, 17, 65537, (1 << 32) + 15, (1 << 63) + 1, (1 << 64) - 1]


def modulus(rng, n_len):
    m = rng.getrandbits(8 * n_len)
    return m | (1 << (8 * n_len - 1)) | 1


def c_bytes(name, value, n_len):
    data = value.to_bytes(n_len, "big")
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return "static const uint8_t %s[%d] = {\n%s\n};\n" % (name, n_len, "\n".join(lines))


def main():
    rng = random.Random(189)
    out = [
        "// Generated by test/gen_rsa_exp_vectors.py; regenerate, never edit.",
        "// Known answers for rsa_mont64_public_exp: pow(base, e, m) from Python.",
        "#ifndef CH_RSA_EXP_VECTORS_H",
        "#define CH_RSA_EXP_VECTORS_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]
    rows = []
    for index, n_len in enumerate(LENGTHS):
        m = modulus(rng, n_len)
        e = EXPONENTS[index % len(EXPONENTS)]
        # Every third base is at or above the modulus.
        base = rng.getrandbits(8 * n_len)
        if index % 3 == 0:
            base = max(base, m)
        out.append(c_bytes("exp_m_%d" % index, m, n_len))
        out.append(c_bytes("exp_base_%d" % index, base, n_len))
        out.append(c_bytes("exp_out_%d" % index, pow(base, e, m), n_len))
        rows.append("    {exp_m_%d, exp_base_%d, exp_out_%d, %d, %d, 0x%xull},"
                    % (index, index, index, n_len, m.bit_length(), e))
    out.append("typedef struct {")
    out.append("    const uint8_t *m;")
    out.append("    const uint8_t *base;")
    out.append("    const uint8_t *out;")
    out.append("    size_t len;")
    out.append("    size_t bits;")
    out.append("    uint64_t e;")
    out.append("} rsa_exp_vector;")
    out.append("")
    out.append("static const rsa_exp_vector rsa_exp_vectors[] = {")
    out.extend(rows)
    out.append("};")
    out.append("")
    out.append("#endif")
    with open("test/rsa_exp_vectors.h", "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()

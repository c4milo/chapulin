#!/usr/bin/env python3
"""Prints src/mlkem_rejection_table.h: the byte orders and the counts that
mlkem_avx2.c's rejection step reads (docs/decisions.md 225).

Usage: python3 tools/mlkem_rejection_table.py > src/mlkem_rejection_table.h

Entry m is for eight 16-bit candidates of which candidate k is kept where bit
k of m is set. Its order lists, for each kept candidate in turn, the two bytes
of that candidate's lane, 2k and 2k + 1, and then 0x80 in each byte that is
left, which PSHUFB writes as zero. Its count is the number of set bits of m.
bin/mlkem_avx2_equiv_test computes every entry by the same rule and compares.
"""

HEADER = """\
// Generated by tools/mlkem_rejection_table.py; regenerate, never edit.
//
// The byte orders and the counts mlkem_avx2.c's rejection step reads
// (docs/decisions.md 225). Entry m is for eight 16-bit candidates of which
// candidate k is kept where bit k of m is set. MLK_REJECTION_ORDER[m] lists,
// for each kept candidate in turn, the bytes 2k and 2k + 1 of its lane, and
// then 0x80 in each byte that is left, which PSHUFB writes as zero.
// MLK_REJECTION_COUNT[m] is the number of set bits of m. Every index comes
// from candidates of the public seed rho, so the tables read nothing secret.
// No source in src/ but mlkem_avx2.c includes this file, and
// bin/mlkem_avx2_equiv_test computes every entry by the rule above and
// compares.
#ifndef CH_MLKEM_REJECTION_TABLE_H
#define CH_MLKEM_REJECTION_TABLE_H

#include <stdint.h>

// clang-format off
"""


def order(mask):
    out = []
    for k in range(8):
        if mask & (1 << k):
            out += [2 * k, 2 * k + 1]
    return out + [0x80] * (16 - len(out))


def main():
    lines = [HEADER]
    lines.append("static const uint8_t MLK_REJECTION_ORDER[256][16] = {\n")
    for mask in range(256):
        body = ", ".join("0x%02x" % b for b in order(mask))
        lines.append("    {%s}, // %s\n" % (body, format(mask, "08b")))
    lines.append("};\n\n")
    lines.append("static const uint8_t MLK_REJECTION_COUNT[256] = {\n")
    for row in range(16):
        body = ", ".join(str(bin(16 * row + i).count("1")) for i in range(16))
        lines.append("    %s,\n" % body)
    lines.append("};\n// clang-format on\n\n#endif\n")
    print("".join(lines), end="")


if __name__ == "__main__":
    main()

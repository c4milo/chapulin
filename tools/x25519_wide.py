#!/usr/bin/env python3
"""Writes the table of multiples of edwards25519's base point that
x25519_wide.c's key generation reads.

Run from the repository root:

    python3 tools/x25519_wide.py table > x25519_wide_table.h

table prints x25519_wide_table.h, the 32 by 8 table x25519_wide_base_mul
reads (x25519_wide_edwards.h): entry [i][j] is (j + 1) * 256^i * B, for B the
base point of edwards25519, as the three field elements y + x, y - x and
2 d x y of the affine point, each in five words of 51 bits, least
significant word first, and each word below 2^51.

Every number here comes from Python's arbitrary-precision integers and from
RFC 7748's definition of the curves, never from the C under test:

- p = 2^255 - 19 and d = -121665 / 121666 (RFC 7748 section 4.1).
- B is the point whose y is 4/5 and whose x is the even root, RFC 8032's
  base point. The script checks that it is on the curve and that the map
  u = (1 + y) / (1 - y) takes it to u = 9, the base point of X25519.
- The multiples come from the affine addition law of the twisted Edwards
  curve -x^2 + y^2 = 1 + d x^2 y^2, which has no exception on this curve:
  d is not a square mod p, and the script checks that too. It checks each
  point against the curve's equation before it prints it.

The script is also the file's formatter. make lint-x25519-wide compares the
checked-in table with what table prints, and make check runs that.
"""

import sys

P = 2**255 - 19
D = -121665 * pow(121666, -1, P) % P
BASE_X = 15112221349535400772501151409588531511454012693041857206046113283949847762202
BASE_Y = 4 * pow(5, -1, P) % P

# The table's shape, which x25519_wide_edwards.h states for the C: one row
# for each pair of four-bit digits of a scalar, eight entries to a row.
ROWS = 32
ENTRIES = 8
WORD_BITS = 51
WORDS = 5


def on_curve(point):
    x, y = point
    return (-x * x + y * y - 1 - D * x * x * y * y) % P == 0


def add(a, b):
    """a + b by the twisted Edwards addition law with a = -1. Its two
    denominators are never zero on this curve, because d is not a square."""
    (x1, y1), (x2, y2) = a, b
    t = D * x1 * x2 * y1 * y2 % P
    x3 = (x1 * y2 + y1 * x2) * pow(1 + t, -1, P) % P
    y3 = (y1 * y2 + x1 * x2) * pow(1 - t, -1, P) % P
    return x3, y3


def multiples():
    """The table as Python integers: row i holds (j + 1) * 256^i * B for j
    from 0 to ENTRIES - 1."""
    assert pow(D, (P - 1) // 2, P) == P - 1, "d is a square, so the addition law has exceptions"
    assert pow(P - 1, (P - 1) // 2, P) == 1, "-1 is not a square, so the addition law has exceptions"
    assert on_curve((BASE_X, BASE_Y)), "B is not on the curve"
    assert BASE_X % 2 == 0, "B's x is not the even root"
    assert (1 + BASE_Y) * pow(1 - BASE_Y, -1, P) % P == 9, "B does not map to u = 9"
    rows = []
    base = (BASE_X, BASE_Y)
    for _ in range(ROWS):
        row = [base]
        for _ in range(1, ENTRIES):
            row.append(add(row[-1], base))
        rows.append(row)
        for _ in range(8):
            base = add(base, base)
    assert all(on_curve(point) for row in rows for point in row), "an entry is off the curve"
    return rows


def element(value):
    """One field element as an initializer of five 51-bit words."""
    words = [(value >> (WORD_BITS * i)) & (2**WORD_BITS - 1) for i in range(WORDS)]
    assert sum(w << (WORD_BITS * i) for i, w in enumerate(words)) == value
    return "{" + ", ".join(f"UINT64_C(0x{word:013x})" for word in words) + "}"


HEADER = """\
// Generated by tools/x25519_wide.py table; regenerate, never edit.
//
// The multiples of edwards25519's base point B that x25519_wide_base_mul adds
// (x25519_wide_edwards.h): entry [i][j] is (j + 1) * 256^i * B as the three
// field elements y + x, y - x and 2 d x y of the affine point, each in five
// words of 51 bits, least significant word first. Each word is below 2^51,
// and each element is below p. A host object holds the table, 30,720 bytes:
// x25519_wide.c includes this file once, inside its CH_CPU_RUNTIME block, and
// no other source of the object includes it. The table is public: it holds
// multiples of B and nothing of any key. The script is also the formatter:
// the off marker below keeps regeneration byte-identical under any
// clang-format version, or none. make lint-x25519-wide fails when this file
// is not what the script prints.
#ifndef CH_X25519_WIDE_TABLE_H
#define CH_X25519_WIDE_TABLE_H

#include <stdint.h>

#define X25519_WIDE_TABLE_ROWS 32   // one row for each pair of four-bit digits
#define X25519_WIDE_TABLE_ENTRIES 8 // the multiples 1 to 8 of the row's power of B

// clang-format off
static const uint64_t X25519_WIDE_TABLE[X25519_WIDE_TABLE_ROWS][X25519_WIDE_TABLE_ENTRIES][3][5] = {
"""


def table():
    out = [HEADER]
    for i, row in enumerate(multiples()):
        out.append(f"    {{ // 256^{i} * B times 1 to {ENTRIES}\n")
        for x, y in row:
            out.append("        {" + element((y + x) % P) + ",\n")
            out.append("         " + element((y - x) % P) + ",\n")
            out.append("         " + element(2 * D * x * y % P) + "},\n")
        out.append("    },\n")
    out.append("};\n// clang-format on\n\n#endif\n")
    sys.stdout.write("".join(out))
    return 0


def main(argv):
    if argv[1:] == ["table"]:
        return table()
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
